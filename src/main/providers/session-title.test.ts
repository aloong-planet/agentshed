// A seam 1 pure function: stripping noise out of session titles.
// **The shapes come from real sampling, not from imagining the spec's list** (2026-08-02, 297 real Claude
// sessions):
// Warmup 188, [cron:…] 92, caveat 13, slash commands 2. The "Conversation info" on the research-phase list
// did not appear in the sample, so no rule is written for it.
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, it, expect } from 'vitest'
import { fingerprint } from './question-index'
import { clipTitle, realUserText } from './session-title'
import { runParseJob } from './token-stats'

describe('realUserText (one message → the real question, or null)', () => {
  it('an ordinary question is returned as is, with whitespace normalised', () => {
    expect(realUserText('  fix a   layout bug\n\nthanks  ')).toBe('fix a layout bug thanks')
  })

  it('whitespace and the empty string count as noise', () => {
    expect(realUserText('')).toBeNull()
    expect(realUserText('   \n\t ')).toBeNull()
  })

  // The most common shape by far: the whole message is that one word (188/297 in the sample)
  it('Warmup: the whole message is discarded', () => {
    expect(realUserText('Warmup')).toBeNull()
    expect(realUserText('  Warmup \n')).toBeNull()
  })

  it('Warmup counts as noise only on exact equality — a real question containing the word is unaffected', () => {
    expect(realUserText('where does the word Warmup come from?')).toBe('where does the word Warmup come from?')
  })

  // The real shape: what follows [cron:<uuid> <name>] is **the actual instruction** and must not be
  // discarded with it
  it('the cron marker: only the bracket is stripped, keeping the instruction after it', () => {
    expect(
      realUserText('[cron:95a214a4-0021-44ea-a831-f5c851b11d77 hackernews-daily-top5] fetch today top 5 topics via the Hacker News API')
    ).toBe('fetch today top 5 topics via the Hacker News API')
  })

  it('nothing after the cron marker → the whole message is discarded', () => {
    expect(realUserText('[cron:abc def]')).toBeNull()
  })

  it('a caveat block is discarded whole', () => {
    expect(
      realUserText('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>')
    ).toBeNull()
  })

  // The second layer of noise, surfacing only after caveat and command invocations are stripped
  // (measured 7/144)
  it('local-command output is discarded whole (the same family as caveat)', () => {
    expect(realUserText('<local-command-stdout>Set model to Fable 5</local-command-stdout>')).toBeNull()
  })

  it('an image marker inside a real question is not noise — seen once, and no stripping rule is written for it', () => {
    expect(realUserText('[Image #1] the dates in this chart look sparse')).toBe('[Image #1] the dates in this chart look sparse')
  })

  it('an injected skill body is discarded whole', () => {
    expect(realUserText('Base directory for this skill: /Users/x/.claude/skills/tdd # TDD red before green')).toBeNull()
  })

  // The real shape: the user's actual input is inside command-args
  it('a slash command: take the contents of command-args', () => {
    expect(
      realUserText(
        '<command-message>superpowers:brainstorming</command-message> <command-name>/superpowers:brainstorming</command-name> <command-args>I want to build a self-study app</command-args>'
      )
    ).toBe('I want to build a self-study app')
  })

  it('a slash command with empty args (such as /clear) → the whole message is discarded', () => {
    expect(
      realUserText('<command-name>/clear</command-name> <command-message>clear</command-message> <command-args></command-args>')
    ).toBeNull()
  })

  it('a command-name with no args tag at all → discarded whole (it is a command invocation, not a question)', () => {
    expect(realUserText('<command-name>/compact</command-name>')).toBeNull()
  })
})

describe('clipTitle (a noise-stripped question → a title)', () => {
  // The responsibility of "walking forward to find the first real question" moved to the indexer on
  // 2026-08-04 (ticket 03b),
  // covered in question-index.test.ts (noise is not a question / no real question anywhere → an empty
  // index).
  // What remains here is truncation, plus one regression guard: clipTitle **must not** strip again.
  it('an over-long title is truncated by code point with an ellipsis added', () => {
    // '★' is 3-byte UTF-8: clipTitle truncates by code point, and with an ASCII fixture a byte-based
    // implementation would pass this case too.
    const t = clipTitle('★'.repeat(200))
    expect([...t]).toHaveLength(61)
    expect(t.endsWith('…')).toBe(true)
  })

  it('a title under the cap is returned as is, with no ellipsis', () => {
    expect(clipTitle('★short★')).toBe('★short★')
  })

  it('no longer strips — stripping is not idempotent, and a second pass would discard the already-stripped content as noise', () => {
    // `[cron:x] Warmup` strips through realUserText to 'Warmup'; if clipTitle stripped again
    // it would become null and the session would vanish from the list.
    expect(realUserText('[cron:abc scheduled] Warmup')).toBe('Warmup')
    expect(clipTitle('Warmup')).toBe('Warmup')
  })
})

// Claude Code's and Codex's question indexes and titles apply these same rules in the engine module
// (engine/src/text/mod.rs), while this file still serves every side's question text on the session page and in both
// searches. One message per shape above, and the text-level edges, go through both: a session file of that one
// question parsed by the module lists the question exactly when realUserText keeps it, under clipTitle's title and
// fingerprint's value. Each copy is the other's expected value: what is held is that they agree, so an edit to one
// alone goes red here.
describe('the engine module applies these rules to a question', () => {
  const ch = (...codes: number[]): string => String.fromCodePoint(...codes)
  const MESSAGES = [
    '  fix a   layout bug\n\nthanks  ',
    '',
    '   \n\t ',
    'Warmup',
    '  Warmup \n',
    'where does the word Warmup come from?',
    '[cron:95a214a4-0021-44ea-a831-f5c851b11d77 hackernews-daily-top5] fetch today top 5 topics via the Hacker News API',
    '[cron:abc def]',
    '[cron:abc scheduled] Warmup',
    '[cron:no closing bracket',
    '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>',
    '<local-command-stdout>Set model to Fable 5</local-command-stdout>',
    '[Image #1] the dates in this chart look sparse',
    'Base directory for this skill: /Users/x/.claude/skills/tdd # TDD red before green',
    '<command-message>superpowers:brainstorming</command-message> <command-name>/superpowers:brainstorming</command-name> <command-args>I want to build a self-study app</command-args>',
    '<command-name>/clear</command-name> <command-message>clear</command-message> <command-args></command-args>',
    '<command-name>/compact</command-name>',
    '<command-name>/x</command-name> <command-args> spaced   args </command-args> <command-args>second</command-args>',
    'The following is the Codex agent history whose request action you are assessing.',
    '<task-notification>\n<task-id>af7263af923d8a8f5</task-id>',
    '<codex_delegation>\n  <source>parent</source>',
    // Every character JavaScript's trim and \s take, and the line terminators among them
    `${ch(0x3000)}wide${ch(0xa0)}and${ch(0x2028)}line${ch(0xfeff)}space${ch(0x205f)}`,
    `${ch(0x200b)}a zero-width space is no white space`,
    '★'.repeat(200),
    `${'a'.repeat(58)}${ch(0x1f600)}${ch(0x1f600)}more`,
    `${'b'.repeat(59)}${String.fromCharCode(0xd800)}after a lone surrogate`
  ]

  it.each(['claude', 'codex'] as const)('lists, titles and fingerprints each %s question as these rules do', async (side) => {
    const dir = mkdtempSync(join(tmpdir(), 'agentshed-title-'))
    try {
      const mismatches: string[] = []
      for (const [i, message] of MESSAGES.entries()) {
        const file = join(dir, `rollout-title-${i}.jsonl`)
        const timestamp = '2026-07-30T10:00:00.000Z'
        const line =
          side === 'claude'
            ? { type: 'user', timestamp, message: { role: 'user', content: message } }
            : { timestamp, type: 'event_msg', payload: { type: 'user_message', message } }
        writeFileSync(file, `${JSON.stringify(line)}\n`)
        const parsed = await runParseJob(
          side === 'claude'
            ? { kind: 'claude', file, projectKey: '', listed: true }
            : {
                kind: 'codex',
                file,
                projectKey: '',
                meta: { subagent: false, sessionId: null, parentId: null, forkedAt: null, paginated: false },
                threadName: undefined
              }
        )
        if (parsed?.agg.kind !== side) throw new Error(`no ${side} entry for message ${i}`)
        const kept = realUserText(message)
        const want = {
          questions: kept === null ? 0 : 1,
          title: kept === null ? `rollout-title-${i}` : clipTitle(kept),
          fingerprint: kept === null ? null : fingerprint(kept)
        }
        const got = { questions: parsed.agg.questions.length, title: parsed.agg.title, fingerprint: parsed.agg.questions[0]?.[6] ?? null }
        if (JSON.stringify(got) !== JSON.stringify(want)) mismatches.push(`message ${i}: ${JSON.stringify({ got, want })}`)
      }
      expect(mismatches).toEqual([])
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})
