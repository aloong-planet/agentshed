// A question's noise, which the question index, the session's title and the question's text on the session page and in
// both searches strip alike (engine/src/text/mod.rs, `real_user_text` and `clip_title`), for Claude Code and Codex.
// **The shapes come from real sampling, not from imagining the spec's list** (2026-08-02, 297 real Claude sessions):
// Warmup 188, [cron:…] 92, caveat 13, slash commands 2. The "Conversation info" on the research-phase list did not
// appear in the sample, so no rule is written for it.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, it, expect } from 'vitest'
import { threadEngineModule } from '../engine-module'
import { runParseJob } from './token-stats'

const ch = (...codes: number[]): string => String.fromCodePoint(...codes)

/** One human message, the question kept of it (null when the whole of it is noise), and the title that question gives
 * when it is not the question itself */
const MESSAGES: Array<[string, string | null, string?]> = [
  // An ordinary question, its white space normalised
  ['  fix a   layout bug\n\nthanks  ', 'fix a layout bug thanks'],
  // White space and the empty string are noise
  ['', null],
  ['   \n\t ', null],
  // The most common shape by far: the whole message is that one word (188/297 in the sample), and only on exact
  // equality
  ['Warmup', null],
  ['  Warmup \n', null],
  ['where does the word Warmup come from?', 'where does the word Warmup come from?'],
  // The cron marker: what follows [cron:<uuid> <name>] is the actual instruction, kept; nothing after it is noise
  ['[cron:95a214a4-0021-44ea-a831-f5c851b11d77 hackernews-daily-top5] fetch today top 5 topics via the Hacker News API', 'fetch today top 5 topics via the Hacker News API'],
  ['[cron:abc def]', null],
  // Stripping is not idempotent: the title is never stripped again, or this question would vanish from the list
  ['[cron:abc scheduled] Warmup', 'Warmup'],
  ['[cron:no closing bracket', '[cron:no closing bracket'],
  // A caveat block, and local-command output — the second layer of noise, surfacing only after caveat and command
  // invocations are stripped (measured 7/144) — are discarded whole
  ['<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>', null],
  ['<local-command-stdout>Set model to Fable 5</local-command-stdout>', null],
  // An image marker inside a real question is not noise: seen once, and no stripping rule is written for it
  ['[Image #1] the dates in this chart look sparse', '[Image #1] the dates in this chart look sparse'],
  // An injected skill body is discarded whole
  ['Base directory for this skill: /Users/x/.claude/skills/tdd # TDD red before green', null],
  // A slash command: the user's input is what command-args holds, and with none it is an invocation, not a question
  ['<command-message>superpowers:brainstorming</command-message> <command-name>/superpowers:brainstorming</command-name> <command-args>I want to build a self-study app</command-args>', 'I want to build a self-study app'],
  ['<command-name>/clear</command-name> <command-message>clear</command-message> <command-args></command-args>', null],
  ['<command-name>/compact</command-name>', null],
  ['<command-name>/x</command-name> <command-args> spaced   args </command-args> <command-args>second</command-args>', 'spaced args'],
  // Codex's harness text: the guardian's transcript preamble, a task notification, a delegation block
  ['The following is the Codex agent history whose request action you are assessing.', null],
  ['<task-notification>\n<task-id>af7263af923d8a8f5</task-id>', null],
  ['<codex_delegation>\n  <source>parent</source>', null],
  // Every character JavaScript's trim and \s take, and the line terminators among them; a zero-width space is none
  [`${ch(0x3000)}wide${ch(0xa0)}and${ch(0x2028)}line${ch(0xfeff)}space${ch(0x205f)}`, 'wide and line space'],
  [`${ch(0x200b)}a zero-width space is no white space`, `${ch(0x200b)}a zero-width space is no white space`],
  // An over-long title is clipped at 60 code points with an ellipsis: a three-byte character, a surrogate pair and a
  // lone surrogate each count one
  ['\u2605'.repeat(200), '\u2605'.repeat(200), `${'\u2605'.repeat(60)}\u2026`],
  [`${'a'.repeat(58)}${ch(0x1f600)}${ch(0x1f600)}more`, `${'a'.repeat(58)}${ch(0x1f600)}${ch(0x1f600)}more`, `${'a'.repeat(58)}${ch(0x1f600)}${ch(0x1f600)}\u2026`],
  [`${'b'.repeat(59)}${String.fromCharCode(0xd800)}after a lone surrogate`, `${'b'.repeat(59)}${String.fromCharCode(0xd800)}after a lone surrogate`, `${'b'.repeat(59)}${String.fromCharCode(0xd800)}\u2026`]
]

describe('a question\'s noise, stripped alike by the index, the title and the question\'s text', () => {
  it.each(['claude', 'codex'] as const)('lists, titles and shows each %s message\'s question as written beside it', async (side) => {
    const dir = mkdtempSync(join(tmpdir(), 'agentshed-title-'))
    try {
      const got: Array<{ questions: number; title: string | null; text: string | null }> = []
      for (const [i, [message]] of MESSAGES.entries()) {
        const file = join(dir, `rollout-title-${i}.jsonl`)
        const timestamp = '2026-07-30T10:00:00.000Z'
        const line =
          side === 'claude'
            ? { type: 'user', timestamp, message: { role: 'user', content: message } }
            : { timestamp, type: 'event_msg', payload: { type: 'user_message', message } }
        writeFileSync(file, `${JSON.stringify(line)}\n`)
        const parsed = await runParseJob(
          side === 'claude'
            ? { kind: 'claude', file, projectKey: '', listed: true }
            : {
                kind: 'codex',
                file,
                projectKey: '',
                meta: { subagent: false, sessionId: null, parentId: null, forkedAt: null, paginated: false },
                threadName: undefined
              }
        )
        if (parsed?.agg.kind !== side) throw new Error(`no ${side} entry for message ${i}`)
        // The file is the one line, which is the range the index records when it is a question
        got.push({ questions: parsed.agg.questions.length, title: parsed.agg.title, text: threadEngineModule().questionText(side, readFileSync(file, 'utf8')) })
      }
      expect(got).toEqual(
        MESSAGES.map(([, kept, title], i) => ({ questions: kept === null ? 0 : 1, title: kept === null ? `rollout-title-${i}` : (title ?? kept), text: kept }))
      )
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})
