/** A result as (file, project, stale, [number, text]…) rows, by file name */
function rows(r: GlobalSearchResult): Array<[string, string, boolean, Array<[number, string]>]> {
  return r.sessions
    .map((s): [string, string, boolean, Array<[number, string]>] => [basename(s.file), s.project.name, s.project.stale, s.hits.map((h) => [h.i, h.text])])
    .sort((x, y) => x[0].localeCompare(y[0]))
}

