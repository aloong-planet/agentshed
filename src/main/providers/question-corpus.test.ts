  const CHILD = '019f0000-bbbb-7000-8000-000000000002'
  f.parent = codexFile(`rollout-${PARENT}.jsonl`, [codexMeta(beta, PARENT), codexQ(1, 'parent asks about kiwi'), codexA(2, 'Kiwis are fine.')])
  f.child = codexFile(`rollout-${CHILD}.jsonl`, [codexMeta(beta, CHILD, { forked_from_id: PARENT }, 3), codexQ(3, 'parent asks about kiwi'), codexQ(4, 'child asks about mango')])
