/** One scan and token build, as the main process runs them, and the corpus's listed set from both */
async function index(engine: TokenEngine): Promise<CorpusProject[]> {
  const snap = await scan(roots(), { now: () => Date.now() })
  const claudePaths = snap.projects.filter((p) => p.sides.includes('claude')).map((p) => p.path)
  const t = await engine.build(roots(), claudePaths, new Set(snap.projects.map((p) => mergeKey(p.path))))
  return corpusProjects(snap.projects, t.perProject)
}

async function corpusOver(opts: CorpusOptions = {}): Promise<{ corpus: QuestionCorpus; engine: TokenEngine; listed: { projects: CorpusProject[] } }> {
  const engine = new TokenEngine(join(dir, 'cache'))
  const listed = { projects: await index(engine) }
  const corpus = new QuestionCorpus(engine, () => ({ roots: roots(), projects: listed.projects }), opts)
  return { corpus, engine, listed }
}

/**
 * The corpus's file reads, counted at its reader — the boundary to the file system. Counting them is the
 * requirement itself (REQ-002/AC-03, REQ-004/AC-02), not an internal call count; the reads are the real
 * range reader's.
 */
function countingReader(): { reads: Map<string, number>; read: NonNullable<CorpusOptions['read']> } {
  const reads = new Map<string, number>()
  return {
    reads,
    read: (file, ranges, limit) => {
      reads.set(basename(file), (reads.get(basename(file)) ?? 0) + 1)
      return readRanges(file, ranges, limit)
    }
  }
}

