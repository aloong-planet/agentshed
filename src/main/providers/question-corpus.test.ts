describe('a reading under way, and one that fails (REQ-002/AC-02, S15, S16)', () => {
  it('a search started while the texts are being read waits for them, then hits', async () => {
    mkHome()
    let release = (): void => {}
    const held = new Promise<void>((r) => { release = r })
    const { corpus } = await corpusOver({ pause: () => held })
    const loading = corpus.load()
    let answered = false
    const searching = corpus.search('kiwi').then((r) => { answered = true; return r })
    await new Promise((r) => setTimeout(r, 50))
    expect(answered).toBe(false)
    release()
    expect(rows(await searching)).toEqual(KIWI)
    await loading
  })

  it('a reading that fails as a whole fails the search too, never as no hits; the next load reads again', async () => {
    mkHome()
    let failures = 2
    const { corpus } = await corpusOver({
      pause: () => {
        if (failures === 0) return Promise.resolve()
        failures--
        return Promise.reject(new Error('reading failed'))
      }
    })
    await expect(corpus.load()).rejects.toThrow('reading failed')
    await expect(corpus.search('kiwi')).rejects.toThrow('reading failed')
    await corpus.load()
    expect(rows(await corpus.search('kiwi'))).toEqual(KIWI)
  })
})

