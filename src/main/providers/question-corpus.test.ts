const enc = (p: string): string => p.replace(/[^a-zA-Z0-9]/g, '-')
const TS = (min: number): string => new Date(Date.UTC(2026, 9, 1, 10, min)).toISOString()

/** A Claude session in a real session's shape: each line chained to the one before it */
function claudeSession(cwd: string, name: string, turns: Array<{ q: string; a?: string }>, opts: { nested?: string } = {}): string {
  const sid = `sid-${name}`
  const lines: string[] = []
  let parent: string | null = null
  const push = (o: Record<string, unknown>, min: number): void => {
    const uuid = `${sid}-${lines.length}`
    lines.push(JSON.stringify({ parentUuid: parent, isSidechain: false, ...o, uuid, timestamp: TS(min), userType: 'external', entrypoint: 'cli', cwd, sessionId: sid, version: '2.1.0', gitBranch: 'main' }))
    parent = uuid
  }
  push({ type: 'user', message: { role: 'user', content: '<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>' }, isMeta: true }, 0)
  turns.forEach((t, k) => {
    push({ type: 'user', message: { role: 'user', content: t.q } }, k * 2 + 1)
    push({ type: 'assistant', message: { role: 'assistant', model: 'claude-fable-5', content: [{ type: 'text', text: t.a ?? 'Done.' }, { type: 'tool_use', id: `tu-${name}-${k}`, name: 'Bash', input: { command: 'ls' } }], usage: { input_tokens: 10, output_tokens: 5, cache_read_input_tokens: 0, cache_creation_input_tokens: 0 } } }, k * 2 + 2)
    push({ type: 'user', message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: `tu-${name}-${k}`, content: 'two files' }] } }, k * 2 + 2)
  })
  const d = opts.nested ? join(dir, '.claude', 'projects', enc(cwd), opts.nested, 'subagents') : join(dir, '.claude', 'projects', enc(cwd))
  mkdirSync(d, { recursive: true })
  const f = join(d, `${name}.jsonl`)
  writeFileSync(f, lines.join('\n') + '\n')
  return f
}

/** A rollout's first line; a fork's timestamp is its fork moment, which its replayed copies carry too */
/** Continue a Claude session's chain with more turns, as a live session grows */
function appendClaude(file: string, questions: string[], fromMin: number): void {
  const last = JSON.parse(readFileSync(file, 'utf8').trim().split('\n').pop() as string) as Record<string, unknown>
  let parent = last['uuid'] as string
  const out = questions.map((q, k) => {
    const uuid = `${parent}-n${k}`
    const line = JSON.stringify({ parentUuid: parent, isSidechain: false, type: 'user', message: { role: 'user', content: q }, uuid, timestamp: TS(fromMin + k), userType: 'external', entrypoint: 'cli', cwd: last['cwd'], sessionId: last['sessionId'], version: '2.1.0', gitBranch: 'main' })
    parent = uuid
    return line
  })
  appendFileSync(file, out.join('\n') + '\n')
}

const codexMeta = (cwd: string, id: string, extra: Record<string, unknown> = {}, min = 0): string =>
  JSON.stringify({ timestamp: TS(min), type: 'session_meta', payload: { cwd, id, ...extra } })
const codexQ = (min: number, m: string): string =>
  JSON.stringify({ timestamp: TS(min), type: 'event_msg', payload: { type: 'user_message', message: m } })
const codexA = (min: number, m: string): string =>
  JSON.stringify({ timestamp: TS(min), type: 'event_msg', payload: { type: 'agent_message', message: m } })

function codexFile(name: string, lines: string[]): string {
  const d = join(dir, '.codex', 'sessions', '2026', '10', '01')
  mkdirSync(d, { recursive: true })
  const f = join(d, name)
  writeFileSync(f, lines.join('\n') + '\n')
  return f
}

/** A paginated rollout in the real shape: an ordinal on every line, the question a completed UserMessage item */
function paginated(cwd: string, id: string, question: string): string {
  const item = (ord: number, type: string, extra: Record<string, unknown>): string =>
    JSON.stringify({ timestamp: TS(ord), ordinal: ord, type: 'event_msg', payload: { type: 'item_completed', thread_id: 't', turn_id: 'u', item: { type, id: `i${ord}`, ...extra }, started_at_ms: 1, completed_at_ms: 1 } })
  const usage = { input_tokens: 70, cached_input_tokens: 0, cache_write_input_tokens: 0, output_tokens: 9, reasoning_output_tokens: 0, total_tokens: 79 }
  return codexFile(`rollout-2026-10-01T10-00-00-${id}.jsonl`, [
    JSON.stringify({ timestamp: TS(0), ordinal: 0, type: 'session_meta', payload: { cwd, id } }),
    JSON.stringify({ timestamp: TS(0), ordinal: 1, type: 'turn_context', payload: { model: 'gpt-5.6-sol', cwd } }),
    item(2, 'UserMessage', { content: [{ type: 'text', text: question, text_elements: [] }] }),
    JSON.stringify({ timestamp: TS(3), ordinal: 3, type: 'token_usage_record', payload: { thread_id: 't', turn_id: 'u', session_id: 't', root_turn_id: 'u', response_id: `resp-${id}`, usage, turn_token_usage: usage, thread_token_usage: usage } }),
    item(4, 'AgentMessage', { content: [{ type: 'Text', text: 'It is in the fruit bowl.' }], phase: 'final_answer' })
  ])
}

/** A Grok session directory in the real layout, its question a user_message_chunk */
function grokSession(cwd: string, id: string, question: string): string {
  const d = join(dir, '.grok', 'sessions', encodeURIComponent(cwd), id)
  mkdirSync(d, { recursive: true })
  writeFileSync(join(d, 'summary.json'), JSON.stringify({ info: { id, cwd }, current_model_id: 'grok-4.5' }))
  const f = join(d, 'updates.jsonl')
  const line = (update: Record<string, unknown>): string => JSON.stringify({ timestamp: 1790000000, method: '_x.ai/session/update', params: { sessionId: 's', update } })
  writeFileSync(f, [
    line({ sessionUpdate: 'user_message_chunk', content: { type: 'text', text: question }, _meta: { modelId: 'grok-4.5', promptIndex: 0 } }),
    line({ sessionUpdate: 'agent_message_chunk', content: { type: 'text', text: 'Durian season is short.' } })
  ].join('\n') + '\n')
  return f
}

