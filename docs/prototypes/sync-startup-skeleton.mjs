#!/usr/bin/env node
// Generate docs/prototypes/_shared/startup-skeleton.css from the app's startup skeleton rules in
// src/renderer/src/theme.css: the placeholders the Agents skeleton draws with (StartupSkeleton.tsx's Sk,
// SkLine and the chart and model-bar fills), the pulse, the page-wide refusal of input and the muted tab.
//
// **Why derived rather than copied.** A hand-drawn skeleton drifted from the app's: the app moved every
// text-line placeholder onto a zero-width-space strut so the row keeps the real font's line box, and a
// copy that missed it shifted the fill by a pixel or two. Generated from the app, the placeholders are the
// app's. Where they sit (which slot, how wide) follows AgentsSkeleton in StartupSkeleton.tsx by hand.
//
// Every rule is scoped under .sk-page, the class the app puts on a skeleton's root: a prototype page keeps
// rules of its own, and a placeholder rule must not reach outside the skeleton. The section's rules for the
// title row's hint and the project column's centred hint are not taken: the prototypes draw those with
// _shared/startup-status. Nor is the muted segment rule: it selects the app's buttons, and the prototype's
// segment is drawn with spans, so the page mutes it itself. After editing that section of theme.css, re-run:
//   node docs/prototypes/sync-startup-skeleton.mjs
// `pnpm check:ui --cross` fails when the generated file is stale.
//
// The stylesheet is cut by css-blocks.mjs, which keeps every declaration as the app wrote it; a section
// marker that has moved is an error, not an empty file.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { section, blocks, rule, selectors } from './css-blocks.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = join(HERE, '..', '..', 'src', 'renderer', 'src', 'theme.css')
const OUT = join(HERE, '_shared', 'startup-skeleton.css')

const ROOT = '.sk-page'
const SKELETON = ['/* ── The startup skeleton', '/* ── The Projects list column ── */']
/** The placeholder rules the Agents skeleton draws with, the root's own rule and the muted tab */
const RULES = ['.sk-ph', '.sk-line', '.sk-ph-deep', '.sk-ph-bar', ROOT, `${ROOT} .tab.on`]

const scoped = (s) => s === ROOT || s.startsWith(`${ROOT} `)
const scope = (sel) => selectors(sel).map((s) => (scoped(s) ? s : `${ROOT} ${s}`)).join(',\n')

export function generate(themeCss) {
  const out = []
  for (const { prelude, body } of blocks(section(themeCss, SKELETON))) {
    if (RULES.includes(prelude)) out.push(rule(scope(prelude), body))
    else if (prelude === '@keyframes sk-pulse') out.push(`${prelude} {\n${blocks(body).map((b) => rule(b.prelude, b.body)).join('\n')}\n}`)
    else if (prelude.startsWith('@media') && prelude.includes('prefers-reduced-motion')) {
      const inner = blocks(body).filter((b) => selectors(b.prelude).some((s) => RULES.includes(s)))
      if (inner.length) out.push(`${prelude} {\n${inner.map((b) => rule(scope(b.prelude), b.body)).join('\n')}\n}`)
    }
  }
  for (const want of RULES) {
    if (!out.some((r) => r.startsWith(`${scope(want)} {`))) {
      throw new Error(`theme.css: no ${want} rule in the startup skeleton section — has it changed shape?`)
    }
  }
  return `/* Derived file: generated by sync-startup-skeleton.mjs from src/renderer/src/theme.css (the startup
   skeleton's placeholders: .sk-ph / .sk-line / .sk-ph-deep / .sk-ph-bar, the pulse, .sk-page and its muted
   .tab.on). Do not edit by hand; edit the app's theme and re-run
   \`node docs/prototypes/sync-startup-skeleton.mjs\`. \`pnpm check:ui --cross\` fails when this file is
   stale. Every rule is scoped under .sk-page, the skeleton's root. */
${out.join('\n')}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = generate(readFileSync(SRC, 'utf8'))
  writeFileSync(OUT, css)
  console.log(`✓ _shared/startup-skeleton.css: ${(css.match(/\{\n/g) || []).length} rule(s)`)
}
