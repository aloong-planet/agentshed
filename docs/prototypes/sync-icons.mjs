#!/usr/bin/env node
// Generate docs/prototypes/_shared/icons.js from the renderer's icon module.
//
// **Why derived rather than copied.** Ticket 112 exists because the prototypes kept drawing emoji long
// after the product had moved to inline SVG, and nobody noticed for weeks. Hand-copying the paths into the
// prototypes would plant that same seed again — two lists of the same thing, kept equal by whoever
// remembers. Deriving one from the other removes the question: there is one source, and the prototypes
// hold a generated view of it.
//
// After editing src/renderer/src/icons.tsx, re-run:  node docs/prototypes/sync-icons.mjs
// `pnpm check:ui --cross` fails when the generated file is stale, so forgetting is caught rather than
// discovered later by eye.
//
// Under file:// an ES module import is blocked by CORS, so the output hangs off `window` — the same rule
// that shapes trend-chart.js and model.mmd.js.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = join(HERE, '..', '..', 'src', 'renderer', 'src', 'icons.tsx')
const OUT = join(HERE, '_shared', 'icons.js')

/** Parse the icon module: one entry per exported component, with its inner elements and stroke width. */
export function parseIcons(source) {
  const icons = []
  const re = /export function (\w+)\(\{ size \}[\s\S]*?<Icon size=\{size\}( strokeWidth=\{([\d.]+)\})?>([\s\S]*?)<\/Icon>/g
  for (const m of source.matchAll(re)) {
    const [, name, , strokeWidth, body] = m
    const els = [...body.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\s+([^>]*?)\s*\/>/g)].map(
      ([, tag, attrs]) => `<${tag} ${attrs.trim()} />`
    )
    // An icon that parses to nothing would render as a blank box with no error anywhere — the same silent
    // shape this whole area keeps producing, so it is an error rather than an empty entry.
    if (els.length === 0) throw new Error(`${name}: no inner elements parsed — has icons.tsx changed shape?`)
    icons.push({ name, strokeWidth: strokeWidth ?? '2', els })
  }
  if (icons.length === 0) throw new Error('no icons parsed from icons.tsx — has the file changed shape?')
  return icons
}

export function render(icons) {
  const entries = icons
    .map(
      ({ name, strokeWidth, els }) =>
        `    ${name}: (size) =>\n      svg(size, ${strokeWidth}, '${els.join('')}'),`
    )
    .join('\n')
  return `// Derived file: generated by sync-icons.mjs from src/renderer/src/icons.tsx. Do not edit by hand;
// edit the icon module and re-run \`node docs/prototypes/sync-icons.mjs\`. \`pnpm check:ui --cross\` fails
// when this file is stale.
//
// Usage in a prototype page:  <script src="../_shared/icons.js"></script>  then  ICONS.Folder(16)
// It returns an SVG string rather than an element, because every prototype builds its rows with innerHTML.
;(function () {
  function svg(size, strokeWidth, inner) {
    return (
      '<svg width="' + (size || 14) + '" height="' + (size || 14) + '" viewBox="0 0 24 24" fill="none" ' +
      'stroke="currentColor" stroke-width="' + strokeWidth + '" stroke-linecap="round" ' +
      'stroke-linejoin="round" aria-hidden="true">' + inner + '</svg>'
    )
  }
  window.ICONS = {
${entries}
  }

  // Static slots declare themselves: <span class="ri" data-icon="Folder" data-icon-size="17"></span>.
  // Rows built at runtime call ICONS.Folder(17) directly instead. The attribute form exists because a
  // prototype's markup is read as much as it is run — \`data-icon="Folder"\` says which icon is there,
  // where a pasted <svg> blob says only that some icon is.
  function fill(root) {
    for (const el of (root || document).querySelectorAll('[data-icon]')) {
      const make = window.ICONS[el.getAttribute('data-icon')]
      if (!make) {
        // Loud rather than blank: a typo'd name would otherwise leave an empty box, which is exactly the
        // kind of missing-icon that goes unnoticed.
        el.textContent = '?'
        el.style.outline = '1px dashed red'
        console.error('unknown icon:', el.getAttribute('data-icon'))
        continue
      }
      el.innerHTML = make(Number(el.getAttribute('data-icon-size')) || 14)
    }
  }
  window.ICONS.fill = fill
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => fill())
  else fill()
})()
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const icons = parseIcons(readFileSync(SRC, 'utf8'))
  writeFileSync(OUT, render(icons))
  console.log(`✓ _shared/icons.js: ${icons.length} icon(s) — ${icons.map((i) => i.name).join(', ')}`)
}
