#!/usr/bin/env node
// Generate docs/prototypes/_shared/theme.css from the app's theme tokens in src/renderer/src/theme.css.
//
// **Why derived rather than copied.** Every prototype used to carry its own copy of the app's colours, and
// the copies drifted apart — one page's palettes kept a themed Claude badge and tinted code blocks long after
// the app had dropped both. With one generated sheet there is one source, and the prototypes hold a view of it.
//
// After editing the token blocks at the top of theme.css, re-run:  node docs/prototypes/sync-theme.mjs
// `pnpm check:ui --cross` fails when the generated file is stale.
//
// The stylesheet is read with jsdom's CSS parser. Anything at the root level other than the shapes below
// is an error rather than something skipped, so a new kind of token block cannot go missing silently.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = join(HERE, '..', '..', 'src', 'renderer', 'src', 'theme.css')
const OUT = join(HERE, '_shared', 'theme.css')
const { JSDOM } = createRequire(import.meta.url)('jsdom')

const DARK = '(prefers-color-scheme: dark)'

/** The app's token blocks, in source order: { theme: null | 'blue' | …, dark, decls: [[name, value]] } */
export function parseTheme(source) {
  const sheet = new JSDOM(`<style>${source}</style>`).window.document.styleSheets[0]
  const blocks = []
  const visit = (rule, dark) => {
    if (rule.media) {
      for (const r of rule.cssRules) visit(r, dark || rule.media.mediaText === DARK)
      return
    }
    if (!rule.style) return
    const decls = []
    for (let i = 0; i < rule.style.length; i++) {
      const name = rule.style[i]
      if (name.startsWith('--')) decls.push([name, rule.style.getPropertyValue(name).trim()])
    }
    if (decls.length === 0) return
    const sel = rule.selectorText.trim()
    // A variable set on a descendant belongs to a component, not to the theme
    if (!/^(:root|html)(\[[^\]]*\])*$/.test(sel)) return
    let theme = null
    if (sel !== ':root') {
      const m = sel.match(/^html\[data-theme=['"]?([\w-]+)['"]?\]$/)
      if (!m) throw new Error(`theme.css: unexpected token block "${sel}" — teach sync-theme.mjs its shape`)
      theme = m[1]
    }
    blocks.push({ theme, dark, decls })
  }
  for (const r of sheet.cssRules) visit(r, false)
  if (!blocks.some((b) => b.theme === null && !b.dark)) throw new Error('theme.css: no :root token block — has the file changed shape?')
  return blocks
}

function selector({ theme, dark }) {
  const parts = [dark ? '[data-demo-mode="dark"]' : '', theme ? `[data-demo-theme="${theme}"]` : '']
  return parts.join('') ? `html${parts.join('')}` : ':root'
}

export function render(blocks) {
  const body = blocks
    .map((b) => {
      // The app's native controls and scrollbars follow Electron's nativeTheme; a prototype has none, so the
      // two root blocks say which scheme the browser should draw them in
      const scheme = b.theme === null ? [`  color-scheme: ${b.dark ? 'dark' : 'light'};`] : []
      return `${selector(b)} {\n${[...scheme, ...b.decls.map(([n, v]) => `  ${n}: ${v};`)].join('\n')}\n}`
    })
    .join('\n')
  return `/* Derived file: generated by sync-theme.mjs from the token blocks of src/renderer/src/theme.css. Do not edit
   by hand; edit the app's theme and re-run \`node docs/prototypes/sync-theme.mjs\`. \`pnpm check:ui --cross\`
   fails when this file is stale.

   Every theme × light/dark state of the app's tokens, keyed on the attributes demo-dimensions.js sets on a
   page that follows the theme and the mode:
     <link rel="stylesheet" href="../_shared/theme.css">
     <script src="../demo-dimensions.js" data-follow="mode theme"></script>
   The app takes light or dark from the system; a prototype takes it from the settings prototype, so the
   app's dark media block becomes html[data-demo-mode="dark"]. */
${body}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const blocks = parseTheme(readFileSync(SRC, 'utf8'))
  writeFileSync(OUT, render(blocks))
  console.log(`✓ _shared/theme.css: ${blocks.length} block(s), ${blocks[0].decls.length} token(s) in :root`)
}
