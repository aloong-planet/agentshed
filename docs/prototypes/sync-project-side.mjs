#!/usr/bin/env node
// Generate docs/prototypes/_shared/project-side.css from the app's project column rules in
// src/renderer/src/theme.css: the "Projects list column" section, plus the startup skeleton's rules the
// column draws with while scanning.
//
// **Why derived rather than copied.** The prototypes drew the project column four ways — three widths, an
// outline selection the app had dropped, rows with and without the side count — because each page copied
// the column by hand at a different time. Generated from the app, there is one column.
//
// Every rule is scoped under the shared block's mount, [data-shared-block="project-side"]: the app keeps
// these class names in one global sheet, but a prototype page has rules of its own under some of the same
// names, and unscoped they would style each other. After editing those sections of theme.css, re-run:
//   node docs/prototypes/sync-project-side.mjs
// `pnpm check:ui --cross` fails when the generated file is stale.
//
// The stylesheet is cut by css-blocks.mjs, which keeps every declaration as the app wrote it; a section
// marker that has moved is an error, not an empty file.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { section, blocks, rule, selectors } from './css-blocks.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const SRC = join(HERE, '..', '..', 'src', 'renderer', 'src', 'theme.css')
const OUT = join(HERE, '_shared', 'project-side.css')

const MOUNT = '[data-shared-block="project-side"]'
const COLUMN = ['/* ── The Projects list column ── */', '/* ── Pieces shared by the full-width page']
const SKELETON = ['/* ── The startup skeleton', '/* ── The Projects list column ── */']
/** The skeleton's rules the column uses; the rest of that section belongs to the Agents page */
const SKELETON_RULES = ['.sk-ph', '.sk-line', '.sk-page']
/** Classes the app puts on the column element itself rather than inside it */
const ON_MOUNT = ['.side', '.sk-page']

const scope = (sel) =>
  selectors(sel).map((s) => (ON_MOUNT.includes(s) ? `${MOUNT}${s === '.side' ? '' : s}` : `${MOUNT} ${s}`)).join(',\n')

export function generate(themeCss) {
  const out = []
  for (const { prelude, body } of blocks(section(themeCss, COLUMN))) {
    if (prelude.startsWith('@')) throw new Error(`theme.css: unexpected rule in the project column section: ${prelude.slice(0, 60)}`)
    // The detail area beside the column is the page's own
    if (prelude === '.detail') continue
    out.push(rule(scope(prelude), body))
  }
  for (const { prelude, body } of blocks(section(themeCss, SKELETON))) {
    if (SKELETON_RULES.includes(prelude)) out.push(rule(scope(prelude), body))
    else if (prelude === '@keyframes sk-pulse') out.push(`${prelude} {\n${blocks(body).map((b) => rule(b.prelude, b.body)).join('\n')}\n}`)
    else if (prelude.startsWith('@media') && prelude.includes('prefers-reduced-motion')) {
      // Only the column's own placeholders: the bars belong to the Agents page
      const inner = blocks(body)
        .map((b) => ({ ...b, prelude: selectors(b.prelude).filter((x) => SKELETON_RULES.includes(x)).join(', ') }))
        .filter((b) => b.prelude)
      if (inner.length) out.push(`${prelude} {\n${inner.map((b) => rule(scope(b.prelude), b.body)).join('\n')}\n}`)
    }
  }
  if (!out.some((r) => r.startsWith(`${MOUNT} .row {`))) throw new Error('theme.css: no .row rule in the project column section — has it changed shape?')
  return `/* Derived file: generated by sync-project-side.mjs from src/renderer/src/theme.css (the "Projects list
   column" section and the startup skeleton's .sk-ph / .sk-line / .sk-page). Do not edit by hand; edit the
   app's theme and re-run \`node docs/prototypes/sync-project-side.mjs\`. \`pnpm check:ui --cross\` fails
   when this file is stale. Every rule is scoped under the shared block's mount; see _shared/project-side.js. */
${out.join('\n')}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = generate(readFileSync(SRC, 'utf8'))
  writeFileSync(OUT, css)
  console.log(`✓ _shared/project-side.css: ${(css.match(/\{\n/g) || []).length} rule(s)`)
}
